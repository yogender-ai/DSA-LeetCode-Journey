#include<iostream>
#include<vector>
using namespace std;
int main(){
    vector<int>nums={1,2,3,4};
    cout<<nums[0];
    cout<<'\n'<<nums.at(0);
    cout<<'\n'<<nums.at(5);
    return 0;
}
//Done two pointer revision
